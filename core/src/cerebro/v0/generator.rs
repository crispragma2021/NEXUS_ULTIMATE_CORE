        assert!(paths.contains(&"src/components/ui/button.tsx"));
        assert!(paths.contains(&"src/components/ui/card.tsx"));

        // El App.tsx importa el Button.
        let app = gen.files.iter().find(|f| f.path == "src/App.tsx").unwrap();
