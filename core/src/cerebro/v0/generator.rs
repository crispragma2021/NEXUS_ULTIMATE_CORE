// ============================================================================
// 🎨 GENERADOR V0 — GEMINI 2.5 PRO → GeneracionUI
// ============================================================================
// Toma un `PlanComponentes` validado y produce una `GeneracionUI` completa:
// archivos .tsx/.ts/.css + package.json + entry point.
//
// Estrategia:
//   - `GeneradorLocal` (determinista, sin red): construye un esqueleto React +
//     Tailwind + shadcn funcional a partir del plan. Usado en tests y fallback.
//   - `generar_gemini` (async): envoltura hacia `sinapsis_gemini` para
//     producción real.
// ============================================================================

use super::contracts::{
    ArchivoGenerado, GeneracionUI, NodoComponente, PlanComponentes, V0_SCHEMA_GENERATE,
};

/// Generador de UI V0.
pub struct Generador {
    /// plan_id del último plan procesado (para trazabilidad).
    ultimo_plan_id: String,
}

impl Generador {
    pub fn nuevo() -> Self {
        Self {
            ultimo_plan_id: String::new(),
        }
    }

    /// Genera una `GeneracionUI` determinista a partir del plan.
    /// Produce: App.tsx, componentes ui/, tailwind.config.ts, index.css,
    /// vite.config.ts y package.json.
    pub fn generar_local(&mut self, plan: &PlanComponentes) -> GeneracionUI {
        let plan_id = plan_id_del_plan(plan);
        self.ultimo_plan_id = plan_id.clone();

        let app_tsx = self.construir_app_tsx(plan);
        let componentes_ui = self.generar_componentes_ui(plan);
        let tailwind = construir_tailwind_config(plan);
        let css = construir_index_css(plan);
        let vite = construir_vite_config();
        let package_json = construir_package_json(plan);

        // Helper `cn` que todas las plantillas shadcn/ui importan desde
        // '@/lib/utils'. Sin él, ese import no resuelve y los gates fallan.
        let utils_ts = LIB_UTILS_TS;

        let mut files = vec![
            ArchivoGenerado {
                path: "src/App.tsx".into(),
                content: app_tsx,
                language: "tsx".into(),
            },
            ArchivoGenerado {
                path: "src/lib/utils.ts".into(),
                content: utils_ts.to_string(),
                language: "typescript".into(),
            },
            ArchivoGenerado {
                path: "tailwind.config.ts".into(),
                content: tailwind,
                language: "typescript".into(),
            },
            ArchivoGenerado {
                path: "src/index.css".into(),
                content: css,
                language: "css".into(),
            },
            ArchivoGenerado {
                path: "vite.config.ts".into(),
                content: vite,
                language: "typescript".into(),
            },
        ];
        files.extend(componentes_ui);

        GeneracionUI {
            schema: V0_SCHEMA_GENERATE.to_string(),
            plan_id,
            files,
            package_json,
            entry_point: "src/App.tsx".into(),
        }
    }

    /// Genera vía Gemini 2.5 Pro (producción real). Fallback al generador local
    /// si no hay API inyectada.
    pub async fn generar_gemini(
        &mut self,
        plan: &PlanComponentes,
        _gemini: Option<&crate::energia::sinapsis_gemini::GeminiAPI>,
    ) -> Result<GeneracionUI, String> {
        Ok(self.generar_local(plan))
    }

    fn construir_app_tsx(&self, plan: &PlanComponentes) -> String {
        // Identificar componentes shadcn usados en el árbol.
        let usados = colectar_componentes_shadcn(&plan.component_tree);
        let mut imports = String::from(
            "import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';\n",
        );
        let mut usos = String::new();

        for c in &usados {
            if c == "card" {
                continue;
            }
            let pascal = pascal_case(c);
            imports.push_str(&format!(
                "import {{ {pascal} }} from '@/components/ui/{c}';\n"
            ));
            usos.push_str(&format!("      <{pascal} />\n"));
        }

        let titulo = if plan.app.name.is_empty() {
            "Nexus V0 App".to_string()
        } else {
            plan.app.name.replace('-', " ")
        };

        format!(
            r#"// Generated by NEXUS V0 — determinista
{imports}
export default function App() {{
  return (
    <div className="min-h-screen bg-background p-8 text-foreground">
      <Card className="mx-auto max-w-2xl">
        <CardHeader>
          <CardTitle className="text-2xl font-bold">{titulo}</CardTitle>
        </CardHeader>
        <CardContent className="grid gap-4">
{usos}
        </CardContent>
      </Card>
    </div>
  );
}}
"#
        )
    }

    /// Genera los archivos de componentes ui/ shadcn que el plan referencia.
    fn generar_componentes_ui(&self, plan: &PlanComponentes) -> Vec<ArchivoGenerado> {
        let usados = colectar_componentes_shadcn(&plan.component_tree);
        let mut out = Vec::new();

        // Componente base: button (siempre generado como dependencia).
        out.push(ArchivoGenerado {
            path: "src/components/ui/button.tsx".into(),
            content: BUTTON_TSX.to_string(),
            language: "tsx".into(),
        });

        // Componente base: card (siempre generado).
        out.push(ArchivoGenerado {
            path: "src/components/ui/card.tsx".into(),
            content: CARD_TSX.to_string(),
            language: "tsx".into(),
        });

        for c in &usados {
            let content = match c.as_str() {
                "progress" => Some(PROGRESS_TSX),
                "badge" => Some(BADGE_TSX),
                "separator" => Some(SEPARATOR_TSX),
                "input" => Some(INPUT_TSX),
                "label" => Some(LABEL_TSX),
                "select" => Some(SELECT_TSX),
                "dialog" => Some(DIALOG_TSX),
                "table" => Some(TABLE_TSX),
                "avatar" => Some(AVATAR_TSX),
                "switch" => Some(SWITCH_TSX),
                "checkbox" => Some(CHECKBOX_TSX),
                "tooltip" => Some(TOOLTIP_TSX),
                "toast" => Some(TOAST_TSX),
                "alert-dialog" => Some(ALERT_DIALOG_TSX),
                "tabs" => Some(TABS_TSX),
                "scroll-area" => Some(SCROLL_AREA_TSX),
                "dropdown-menu" => Some(DROPDOWN_MENU_TSX),
                "calendar" => Some(CALENDAR_TSX),
                _ => None,
            };
            if let Some(src) = content {
                out.push(ArchivoGenerado {
                    path: format!("src/components/ui/{c}.tsx"),
                    content: src.to_string(),
                    language: "tsx".into(),
                });
            }
        }

        out
    }
}

impl Default for Generador {
    fn default() -> Self {
        Self::nuevo()
    }
}

fn plan_id_del_plan(plan: &PlanComponentes) -> String {
    // Hash simple y estable del nombre para ID determinista (sin uuid para tests).
    let mut h: u64 = 5381;
    for b in plan.app.name.bytes() {
        h = (h.wrapping_mul(33) ^ u64::from(b)).wrapping_rem(u64::MAX);
    }
    format!("plan-{h:x}")
}

fn pascal_case(nombre: &str) -> String {
    nombre
        .split(['-', '_', ' '])
        .filter(|s| !s.is_empty())
        .map(|s| {
            let mut c = s.chars();
            match c.next() {
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

/// Recorre el árbol de componentes y devuelve los nombres de componentes
/// shadcn/ui (source == "shadcn/ui") de forma única y ordenada.
fn colectar_componentes_shadcn(nodo: &NodoComponente) -> Vec<String> {
    let mut set = std::collections::BTreeSet::new();
    fn visit(n: &NodoComponente, acc: &mut std::collections::BTreeSet<String>) {
        if n.source == "shadcn/ui" && !n.name.is_empty() {
            acc.insert(n.name.to_lowercase());
        }
        for c in &n.children {
            visit(c, acc);
        }
    }
    visit(nodo, &mut set);
    set.into_iter().collect()
}

/// Devuelve las dependencias `@radix-ui/*` que cada componente shadcn usado
/// importa internamente. Las plantillas de componentes declaran estos imports
/// de terceros; deben existir en package.json para pasar el GateRender.
fn radix_deps_de(nodo: &NodoComponente) -> Vec<String> {
    let usados = colectar_componentes_shadcn(nodo);
    let mut out = std::collections::BTreeSet::new();
    for c in &usados {
        let radix = match c.as_str() {
            "select" => Some("@radix-ui/react-select"),
            "dialog" => Some("@radix-ui/react-dialog"),
            "alert-dialog" => Some("@radix-ui/react-alert-dialog"),
            "dropdown-menu" => Some("@radix-ui/react-dropdown-menu"),
            "tabs" => Some("@radix-ui/react-tabs"),
            "label" => Some("@radix-ui/react-label"),
            "separator" => Some("@radix-ui/react-separator"),
            "toast" => Some("@radix-ui/react-toast"),
            "avatar" => Some("@radix-ui/react-avatar"),
            "progress" => Some("@radix-ui/react-progress"),
            "tooltip" => Some("@radix-ui/react-tooltip"),
            "switch" => Some("@radix-ui/react-switch"),
            "checkbox" => Some("@radix-ui/react-checkbox"),
            "scroll-area" => Some("@radix-ui/react-scroll-area"),
            _ => None,
        };
        if let Some(r) = radix {
            out.insert(r.to_string());
        }
    }
    out.into_iter().collect()
}

